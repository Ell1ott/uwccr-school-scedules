export function withStudentEmails<T extends { id: string }>(
  students: T[],
): (T & { email: string | null })[] {
  return students.map((student) => ({
    ...student,
    email: emailForStudentId(student.id),
  }));
}

export function emailsForStudentIds(ids: Iterable<string>): string[] {
  const emails: string[] = [];
  for (const id of ids) {
    const email = emailForStudentId(id);
    if (email) emails.push(email);
  }
  return emails;
}

export function mailtoBcc(
  emails: string[],
  subject: string,
  body?: string,
): string | null {
  if (emails.length === 0) return null;
  const params = new URLSearchParams();
  params.set("bcc", emails.join(","));
  params.set("subject", subject);
  if (body) params.set("body", body);
  return `mailto:?${params.toString()}`;
}
